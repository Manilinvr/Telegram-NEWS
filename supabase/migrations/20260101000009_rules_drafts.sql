-- Черновик, собранный правилами, перестаёт выдаваться за написанный человеком.
--
-- До сих пор значений было два: AI и HUMAN. Когда модель недоступна —
-- исчерпан лимит, кончился баланс, неверный ключ — разбор выполняется
-- набором правил, и такой черновик записывался как HUMAN. Это неправда:
-- человек его не писал и не видел.
--
-- Различие не косметическое. Черновик, сделанный правилами, имеет смысл
-- пересобрать моделью, когда она снова заработает. Черновик, написанный
-- человеком, переписывать нельзя ни при каких обстоятельствах. Пока оба
-- помечены одинаково, отличить их можно только по косвенным признакам, а
-- ошибка стоит потерянной правки редактора.

ALTER TABLE ai_drafts DROP CONSTRAINT IF EXISTS ai_drafts_created_by_check;
ALTER TABLE ai_drafts
  ADD CONSTRAINT ai_drafts_created_by_check
  CHECK (created_by IN ('AI', 'HUMAN', 'RULES'));

-- Уже накопленные записи: правилами сделано то, что помечено человеком,
-- но не имеет ни автора, ни названия модели. Ручная правка всегда
-- сохраняет автора (created_by_user), поэтому под условие не попадает.
UPDATE ai_drafts
   SET created_by = 'RULES'
 WHERE created_by = 'HUMAN'
   AND created_by_user IS NULL
   AND model IS NULL;
