import { z } from 'zod';

/**
 * Настройки публикации, включая автоматическую (ТЗ §13).
 *
 * Автопубликация выключена по умолчанию и включается осознанно: с ней
 * материал уходит в канал без человека, и цена ошибки — не строка в
 * журнале, а опубликованная новость, которую уже увидели читатели.
 *
 * Поэтому у неё есть ограничители, а не просто «вкл/выкл»:
 *
 *  • minConfidence — материалы, в которых модель не уверена, всё равно
 *    идут к человеку. Именно низкая уверенность отмечает случаи с
 *    противоречиями и пробелами в источниках;
 *  • delayMinutes — окно, в котором можно вмешаться: события
 *    дополняются публикациями других каналов ещё какое-то время после
 *    первой, и пост, ушедший мгновенно, рискует оказаться неполным.
 *
 * Проверка лексики, обязательные источники и непустой текст ограничителями
 * не являются: они выполняются для любой публикации и настройками не
 * управляются.
 */

export const publishingSettingsSchema = z.object({
  autoPublish: z.boolean().default(false),

  /** Ниже этого значения материал уходит к человеку. */
  minConfidence: z.number().min(0).max(1).default(0.85),

  /** Пауза перед автоматической отправкой. 0 — отправлять сразу. */
  delayMinutes: z.number().int().min(0).max(180).default(10),

  /**
   * Кто и когда включил автопубликацию. Заполняется сервером, а не
   * интерфейсом: это запись об ответственности, и она не должна зависеть
   * от того, что прислал клиент. От имени этого пользователя выполняются
   * автоматические публикации, и его права проверяются при каждой.
   */
  enabledBy: z.string().uuid().nullable().default(null),
  enabledAt: z.string().nullable().default(null),
});

export type PublishingSettings = z.infer<typeof publishingSettingsSchema>;

export const DEFAULT_PUBLISHING_SETTINGS: PublishingSettings =
  publishingSettingsSchema.parse({});

/** Ключ настройки в таблице settings. Раздел критичный: нужен пароль. */
export const PUBLISHING_SETTING_KEY = 'publishing';
