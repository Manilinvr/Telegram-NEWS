import { z } from 'zod';

/**
 * Расход запросов к модели (ТЗ §8).
 *
 * Бесплатные тарифы считают не токены, а ЗАПРОСЫ в сутки, поэтому важно
 * не то, насколько длинны тексты, а сколько раз система обращается к
 * модели. Обращений два на новость: классификация публикации и разбор
 * события в черновик.
 *
 * Классификация — та половина, без которой можно обойтись: категорию,
 * важность и «новость ли это» правила определяют по ключевым словам
 * заметно хуже модели, но всё же определяют, и ошибку видно модератору
 * сразу. Переписать текст правила не могут вообще. Поэтому при нехватке
 * квоты отключают именно классификацию, а не черновики.
 */

export const aiSettingsSchema = z.object({
  /**
   * Обращаться ли к модели для классификации публикаций.
   *
   * Выключение примерно вдвое сокращает число запросов: черновики
   * продолжают делаться моделью, а категория и важность определяются
   * правилами.
   */
  useModelForClassification: z.boolean().default(true),
});

export type AiSettings = z.infer<typeof aiSettingsSchema>;

export const DEFAULT_AI_SETTINGS: AiSettings = aiSettingsSchema.parse({});

/** Ключ настройки в таблице settings. */
export const AI_SETTING_KEY = 'ai';
