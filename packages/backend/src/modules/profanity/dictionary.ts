/**
 * Правила распознавания запрещённой лексики (ТЗ §7).
 *
 * Устройство словаря:
 *
 *  1. Правила ищут КОРНИ, а не точные слова. Русский мат обладает огромной
 *     словообразовательной продуктивностью: перечислить все формы нельзя,
 *     поэтому шаблоны покрывают корень с допуском на повторы букв и символы-
 *     заполнители (`х*й`).
 *
 *  2. У каждого правила есть собственный список исключений `allow`. Он
 *     проверяется по ЦЕЛОМУ слову, а не по фрагменту: «погребал» содержит
 *     «ебал», но целиком является формой глагола «грести» и матом не является.
 *     Без этого механизма широкие корни давали бы ложные блокировки на вполне
 *     нейтральных новостных текстах.
 *
 *  3. Тяжесть разделена на два уровня. BLOCK — мат: он не может быть разрешён
 *     никакой настройкой. WARN — грубая брань и оскорбления: по умолчанию тоже
 *     блокирует публикацию, но эта политика настраивается владельцем.
 *
 * При изменении словаря ОБЯЗАТЕЛЬНО поднимайте RULES_VERSION: версия
 * сохраняется в отчёте проверки, и по ней можно воспроизвести, по какому
 * набору правил материал был допущен к публикации.
 */

export const RULES_VERSION = '1.0.0';

export type Severity = 'BLOCK' | 'WARN';

export interface ProfanityRule {
  id: string;
  severity: Severity;
  description: string;
  /** Шаблон по нормализованному тексту. Флаг `g` добавляется автоматически. */
  pattern: RegExp;
  /**
   * Слова-исключения. Проверяются по ЦЕЛОМУ слову, содержащему совпадение.
   * Если хотя бы один шаблон совпал — срабатывание отбрасывается.
   */
  allow?: RegExp[];
  /** Алфавит, в котором работает правило. */
  script?: 'cyrillic' | 'latin';
}

/** Класс «символ-заполнитель»: ими заменяют букву при обходе фильтра. */
const FILL = '*#%^&+~';

/** Собрать класс символов вместе с заполнителями. */
const c = (chars: string) => `[${chars}${FILL}]`;

