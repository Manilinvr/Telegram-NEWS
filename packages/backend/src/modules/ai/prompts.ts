/** Собрать пользовательское сообщение с исходными публикациями. */
export function buildEditorialUserMessage(input: {
  posts: Array<{
    index: number;
    sourceTitle: string;
    postedAt: string;
    text: string;
    url: string | null;
  }>;
  transcripts: Array<{ mediaLabel: string; text: string; segments?: string }>;
  categories: Array<{ slug: string; title: string }>;
  existingLocation?: string | null;
}): string {
  const parts: string[] = [];

  parts.push('## Доступные категории\n');
  parts.push(input.categories.map((c) => `- ${c.slug} — ${c.title}`).join('\n'));

  parts.push('\n\n## Публикации источников\n');
  for (const post of input.posts) {
    parts.push(
      `\n### Публикация ${post.index}\n` +
        `Источник: ${post.sourceTitle}\n` +
        `Время публикации: ${post.postedAt}\n` +
        (post.url ? `Ссылка: ${post.url}\n` : '') +
        `Текст:\n"""\n${post.text}\n"""\n`,
    );
  }

  if (input.transcripts.length > 0) {
    parts.push('\n## Транскрипции видео\n');
    parts.push(
      'Используй их только для цитат очевидцев. Неразборчивые фрагменты ' +
        'помечены как [неразборчиво] — НЕ додумывай их содержание.\n',
    );
    for (const transcript of input.transcripts) {
      parts.push(`\n### ${transcript.mediaLabel}\n"""\n${transcript.text}\n"""\n`);
    }
  }

  if (input.existingLocation) {
    parts.push(`\n## Ранее определённое место\n${input.existingLocation}\n`);
  }

  parts.push(
    '\n## Задача\n' +
      'Подготовь структурированный анализ и редакционный черновик по правилам выше. ' +
      'Ответ — только JSON.',
  );

  return parts.join('');
}

export function buildClassificationUserMessage(input: {
  text: string;
  sourceTitle: string;
  postedAt: string;
  categories: Array<{ slug: string; title: string }>;
}): string {
  return (
    '## Доступные категории\n' +
    input.categories.map((c) => `- ${c.slug} — ${c.title}`).join('\n') +
    `\n\n## Публикация\nИсточник: ${input.sourceTitle}\nВремя: ${input.postedAt}\n` +
    `Текст:\n"""\n${input.text}\n"""\n\n## Задача\nКлассифицируй публикацию. Ответ — только JSON.`
  );
}

export function buildDedupUserMessage(a: { text: string; postedAt: string }, b: { text: string; postedAt: string }): string {
  return (
    `## Публикация A (${a.postedAt})\n"""\n${a.text}\n"""\n\n` +
    `## Публикация B (${b.postedAt})\n"""\n${b.text}\n"""\n\n` +
    '## Задача\nОпиши, одно ли это событие. Ответ — только JSON.'
  );
}
