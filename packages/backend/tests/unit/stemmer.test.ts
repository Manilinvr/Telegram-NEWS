import { describe, expect, it } from 'vitest';
import { stemRussian } from '../../src/lib/stemmer.js';

/**
 * Сверка с эталонной реализацией Snowball для русского языка.
 *
 * Значения получены из референсного стеммера snowballstemmer. Тест
 * фиксирует именно их, а не «интуитивно ожидаемые» основы: алгоритм
 * разбирает омонимичные окончания по правилу, а не по смыслу, и это
 * нормальное, задокументированное его поведение.
 */
describe('Стеммер русского языка', () => {
  it.each([
    ['пожара', 'пожар'],
    ['пожаре', 'пожар'],
    ['набережная', 'набережн'],
    ['набережной', 'набережн'],
    ['столкнулись', 'столкнул'],
    ['произошло', 'произошл'],
    ['улице', 'улиц'],
    ['движение', 'движен'],
    ['сотрудники', 'сотрудник'],
    ['машины', 'машин'],
    ['фестиваль', 'фестивал'],
    ['автомобиль', 'автомобил'],
    ['автомобилях', 'автомобил'],
    // Окончание «или» — глагольное («ходили»), поэтому «автомобили»
    // разбирается как глагол. Так же ведёт себя эталонная реализация.
    ['автомобили', 'автомоб'],
    ['ходили', 'ход'],
  ])('%s → %s', (word, expected) => {
    expect(stemRussian(word)).toBe(expected);
  });

  it('не трогает короткие слова и не-кириллицу', () => {
    expect(stemRussian('и')).toBe('и');
    expect(stemRussian('дом')).toBe('дом');
    expect(stemRussian('Tesla')).toBe('tesla');
    expect(stemRussian('М-4')).toBe('м-4');
  });

  it('ё и е считаются одной буквой', () => {
    expect(stemRussian('ёлка')).toBe(stemRussian('елка'));
  });

  it('не выбрасывает исключений на пустой строке', () => {
    expect(() => stemRussian('')).not.toThrow();
    expect(stemRussian('')).toBe('');
  });
});
